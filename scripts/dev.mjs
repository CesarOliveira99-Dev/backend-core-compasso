import {spawn} from 'node:child_process';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const env={...process.env,SEED_DEMO:process.argv.includes('--demo')?'true':process.env.SEED_DEMO||'false'};
const build=spawn(process.execPath,[require.resolve('typescript/bin/tsc'),'-p','tsconfig.json'],{stdio:'inherit',env});
const code=await new Promise(resolve=>build.on('exit',resolve));
if(code!==0)process.exit(Number(code)||1);
const server=spawn(process.execPath,['dist/main.js'],{stdio:'inherit',env});
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>server.kill(signal));
server.on('exit',code=>process.exit(code??1));
